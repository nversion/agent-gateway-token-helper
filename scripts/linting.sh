#!/usr/bin/env bash
# Single source of truth for the checks CI runs (the test job in .github/workflows/build.yaml
# calls this script). Usage: scripts/linting.sh [--fix]
#   --fix  first rewrite imports with goimports (needs goimports on PATH)

set -euo pipefail
cd "$(dirname "$0")/.."

step() {
    echo
    echo "==> $*"
    "$@"
}

if [[ "${1:-}" == "--fix" ]]; then
    echo "==> goimports"
    goimports -local github.com/nversion/agent-gateway-token-helper -w $(git ls-files '*.go')
fi

step go build ./...
step go test ./...
step go test -race ./...
step go test -tags integration ./test/...
step go vet -tags integration ./...
# The store, lock and browser packages have per-OS files; vet the ones the host OS doesn't build.
step env GOOS=windows go vet -tags integration ./...
step env GOOS=linux go vet -tags integration ./...
step env GOOS=darwin CGO_ENABLED=0 go vet ./...
step go tool staticcheck -tags integration ./...
step go tool govulncheck ./...
step golangci-lint run ./...
step env GOOS=windows golangci-lint run ./...
step env GOOS=linux golangci-lint run ./...

echo
echo "All checks passed"
